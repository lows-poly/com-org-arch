
TITLE	LAB22
.MODEL	SMALL
.STACK	100H

.DATA
CR		EQU	0DH
LF		EQU	0AH

NL		DB	CR, LF, '$'
CHAR1		DB	?
CHAR2		DB	?

.CODE
MAIN	PROC
;initialise DS
	MOV	AX, @DATA
	MOV	DS, AX

;show ?
	MOV	AH, 2
	MOV	DL, '?'
	INT	21H

;read char
	MOV	AH, 1

	INT	21H
	MOV	CHAR1, AL
	INT	21H
	MOV	CHAR2, AL

;compare
	MOV	BL, CHAR1
	CMP	BL, CHAR2

	JG	EXCHANGE
	JMP	DISPLAY

EXCHANGE:
	MOV	CL, CHAR1
	MOV	CH, CHAR2
	XCHG	CL, CH
	MOV	CHAR1, CL
	MOV	CHAR2, CH
	JMP	DISPLAY

DISPLAY:
	;next-line
	LEA	DX, NL
	MOV	AH, 9
	INT	21H

	MOV	AH, 2

	MOV	DL, CHAR1
	INT	21H
	MOV	DL, CHAR2
	INT	21H

;DOS exit
	MOV	AH, 4CH
	INT	21H

MAIN	ENDP
	END	MAIN
