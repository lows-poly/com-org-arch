TITLE	LAB22
.MODEL	SMALL
.STACK	100H

.DATA
CR		EQU	0DH
LF		EQU	0AH

GRADE_A		EQU	65
GRADE_B		EQU	66
GRADE_C		EQU	67
GRADE_D		EQU	68
GRADE_F		EQU	70

A_THRESHOLD	EQU	80
B_THRESHOLD	EQU	70
C_THRESHOLD	EQU	60
D_THRESHOLD	EQU	50

SCORE		EQU	40

.CODE
MAIN	PROC
;initialise DS
	MOV	AX, @DATA
	MOV	DS, AX

;compare A
	MOV	BX, SCORE
	CMP	BX, A_THRESHOLD
	JGE	SET_PRINT_A

;compare B
	MOV	BX, SCORE
	CMP	BX, B_THRESHOLD
	JGE	SET_PRINT_B

;compare C
	MOV	BX, SCORE
	CMP	BX, C_THRESHOLD
	JGE	SET_PRINT_C

;compare D
	MOV	BX, SCORE
	CMP	BX, D_THRESHOLD
	JGE	SET_PRINT_D

;compare F
	MOV	BX, SCORE
	CMP	BX, D_THRESHOLD
	JL	SET_PRINT_F

SET_PRINT_A:
	MOV	AH, 2
	MOV	DL, GRADE_A
	JMP	DISPLAY

SET_PRINT_B:
	MOV	AH, 2
	MOV	DL, GRADE_B
	JMP	DISPLAY

SET_PRINT_C:
	MOV	AH, 2
	MOV	DL, GRADE_C
	JMP	DISPLAY

SET_PRINT_D:
	MOV	AH, 2
	MOV	DL, GRADE_D
	JMP	DISPLAY

SET_PRINT_F:
	MOV	AH, 2
	MOV	DL, GRADE_F

DISPLAY:
	INT	21H

;DOS exit
	MOV	AH, 4CH
	INT	21H

MAIN	ENDP
	END	MAIN
