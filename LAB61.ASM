TITLE	LAB61
.MODEL	SMALL
.STACK	100H

.DATA
CR		EQU	0DH
LF		EQU	0AH
NAME_LEN	EQU	12
NUM_SCORES	EQU	4
NUM_STUDENTS	EQU	4

NL		DB	CR, LF, '$'

CLASS		DB	'MARY ALLEN  ',	67, 45, 98, 33
		DB	'SCOTT BAYLIS',	70, 56, 87, 44
		DB	'GEORGE FRANK',	82, 72, 89, 40
		DB	'SAM WONG    ',	78, 76, 92, 60

BUF		DW	?

.CODE
MAIN	PROC
;initialise DS
	MOV	AX, @DATA
	MOV	DS, AX

	MOV	SI, 0
	MOV	CL, NUM_STUDENTS

ROW:
	MOV	BL, NAME_LEN
	MOV	BUF, 0

PRINT_NAME:
	MOV	AH, 02H
	MOV	DL, CLASS[SI]
	INT	21H
	INC	SI

	DEC	BL
	JNZ	PRINT_NAME

	MOV	BH, NUM_SCORES

CALC_SCORE:
	XOR	AH, AH
	MOV	AL, CLASS[SI]
	ADD	BUF, AX
	INC	SI

	DEC	BH
	JNZ	CALC_SCORE

	;avg
	MOV	AX, BUF
	XOR	DX, DX
	MOV	BX, NUM_SCORES
	IDIV	BX
	CALL	OUTDEC

	;next-line
	MOV	AH, 09H
	LEA	DX, NL
	INT	21H

	DEC	CL
	JNZ	ROW

;dos exit
	MOV	AH, 4CH
	INT	21H

MAIN	ENDP
INCLUDE	OUTDEC.ASM	; include OUTDEC
	END	MAIN
