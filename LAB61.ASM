TITLE	LAB61
.MODEL	SMALL
.STACK	100H

.DATA
CR		EQU	0DH
LF		EQU	0AH

NL		DB	CR, LF, '$'

CLASS		DB	'MARY ALLEN  ',	67, 45, 98, 33
		DB	'SCOTT BAYLIS',	70, 56, 87, 44
		DB	'GEORGE FRANK',	82, 72, 89, 40
		DB	'SAM WONG    ',	78, 76, 92, 60

AVG_MARY	DB	?
AVG_SCOTT	DB	?
AVG_GEORGE	DB	?
AVG_SAM		DB	?

BUF		DW	?

.CODE
MAIN	PROC
;initialise DS
	MOV	AX, @DATA
	MOV	DS, AX

	MOV	SI, 0
	MOV	CL, 4
	XOR	AX, AX

ROW:
	MOV	BL, 0
	MOV	BH, 0
	MOV	CH, 0

	MOV	BUF, 0
	XOR	AX, AX
	XOR	AH, AH
	XOR	AL, AL

	DEC	CL
	CMP	CL, 0
	JZ	EXIT

PRINT_NAME:
	MOV	AH, 02H
	MOV	DL, CLASS[SI]
	INT	21H

	INC	SI
	INC	BL
	CMP	BL, 12
	JNZ	PRINT_NAME

ADD_SCORE:
	MOV	AL, CLASS[SI]
	XOR	AH, AH
	ADD	BUF, AX
	MOV	AX, BUF

	INC	BH
	CMP	BH, 4
	JNZ	ADD_SCORE
	CALL	OUTDEC

	MOV	AH, 09H
	LEA	DX, NL
	INT	21H

	JMP	ROW

EXIT:
	MOV	AH, 4CH
	INT	21H

MAIN	ENDP
INCLUDE	OUTDEC.ASM	; include OUTDEC
	END	MAIN
