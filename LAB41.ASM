TITLE	LAB41
.MODEL	SMALL
.STACK	100H

.DATA
CR		EQU	0DH
LF		EQU	0AH
START_CHAR	EQU	80H

NL		DB	CR, LF, '$'

.CODE
MAIN	PROC
;initialise DS
	MOV	AX, @DATA
	MOV	DS, AX

	MOV	DH, START_CHAR

RESET_LOOP_COUNTER:
	MOV	CX, 10

LOOP_:
	;print
	MOV	AH, 02H
	MOV	DL, DH
	INT	21H

	;FFh?
	CMP	DH, FFH
	JZ	EXIT

	;pr blank
	MOV	DL, ' '
	INT	21H

	;loop again
	INC	DH
	LOOP	LOOP_

;end_loop
	MOV	AH, 02H
	MOV	DL, CR
	INT	21H
	MOV	DL, LF
	INT	21H

	CMP	DH, FFH
	JNZ	RESET_LOOP_COUNTER

EXIT:
	MOV	AH, 4CH
	INT	21H

MAIN	ENDP
	END	MAIN
