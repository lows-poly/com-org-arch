TITLE	LAB32
.MODEL	SMALL
.STACK	100H

.DATA
CR	EQU	0DH
LF	EQU	0AH

NL	DB	CR, LF, '$'

COR	DB	"Correct$"
INCOR	DB	"Incorrect$"

.CODE
MAIN	PROC
;initialise DS
	MOV	AX, @DATA
	MOV	DS, AX

;start
	MOV	AX, 0
	MOV	BX, 1
	MOV	CX, 0

START_LOOP:
	CMP	CX, 100
	JE	PRINT
	CMP	BX, 0
	JE	MINUS
	JMP	PLUS
MINUS:
	SUB	AX, CX
	INC	CX
	MOV	BX, 1
	JMP	START_LOOP
PLUS:
	ADD	AX, CX
	INC	CX
	MOV	BX, 0
	JMP	START_LOOP

PRINT:
	CMP	AX, -50
	JE	PR_COR
PR_INCOR:
	MOV	AH, 09H
	LEA	DX, INCOR
	INT	21H
	JMP	EXIT
PR_COR:
	MOV	AH, 09H
	LEA	DX, COR
	INT	21H

EXIT:
	MOV	AH, 4CH
	INT	21H

MAIN	ENDP
	END	MAIN
