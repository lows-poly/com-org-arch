TITLE	LAB31
.MODEL	SMALL
.STACK	100H

.DATA
CR		EQU	0DH
LF		EQU	0AH

NL		DB	CR, LF, '$'

HEX_PROMPT	DB	"ENTER A HEX DIGIT: $"
DEC_PROMPT	DB	"IN DECIMAL IT IS $"
AGAIN_PROMPT	DB	"DO YOU WANT TO DO IT AGAIN? $"
ILLEGAL_PROMPT	DB	"ILLEGAL CHARACTER - ENTER 0..9 OR A..F: $"

CHAR		DB	?

.CODE
MAIN	PROC
;initialise DS
	MOV	AX, @DATA
	MOV	DS, AX

START:
	MOV	AH, 09H
	LEA	DX, HEX_PROMPT;
	INT	21H

READ_CHAR:
	MOV	AH, 01H
	INT	21H
	MOV	CHAR, AL
	;next_line
	MOV	AH, 09H
	LEA	DX, NL
	INT	21H

;validation
	CMP	BX, 01
	JE	IF_AGAIN
	MOV	BX, 0
;if 0-9
	CMP	CHAR, '0'
	JB	ILLEGAL
	CMP	CHAR, '9'
	JLE	PRINT
;endif 0-9
;if A-F
	CMP	CHAR, 'A'
	JB	ILLEGAL
	CMP	CHAR, 'F'
	JLE	HEX_TO_DEC
;endif A-F

ILLEGAL:
	MOV	AH, 09H
	LEA	DX, ILLEGAL_PROMPT
	INT	21H
	JMP	READ_CHAR

HEX_TO_DEC:
	;prompt
	MOV	AH, 09H
	LEA	DX, DEC_PROMPT
	INT	21H
	;first_digit (1)
	MOV	AH, 02H
	MOV	DL, '1'
	INT	21H
	;second_digit (0-5)
	SUB	CHAR, 11H
	MOV	DL, CHAR
	INT	21H
	;next_line
	MOV	AH, 09H
	LEA	DX, NL
	INT	21H
	JMP	AGAIN

PRINT:
	;prompt
	MOV	AH, 09H
	LEA	DX, DEC_PROMPT
	INT	21H
	;print char
	MOV	AH, 02H
	MOV	DL, CHAR
	INT	21H
	;next_line
	MOV	AH, 09H
	LEA	DX, NL
	INT	21H

AGAIN:
	MOV	AH, 09H
	LEA	DX, AGAIN_PROMPT
	INT	21H
	;cycle_flag
	MOV	BX, 01
	JMP	READ_CHAR
JMP_START_HELPER:
	JMP	START
IF_AGAIN:
	MOV	BX, 0
	CMP	CHAR, 'y'
	JE	JMP_START_HELPER
	CMP	CHAR, 'Y'
	JE	JMP_START_HELPER

EXIT:
	MOV	AH, 4CH
	INT	21H

MAIN	ENDP
	END	MAIN
