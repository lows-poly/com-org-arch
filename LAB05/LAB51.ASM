TITLE	LAB51
.MODEL	SMALL
.STACK	100H

.DATA
CR		EQU	0DH
LF		EQU	0AH

NL		DB	CR, LF, '$'

HOUR		DW	?
MINUTE		DW	?
SECOND		DW	?

.CODE
MAIN	PROC
;initialise DS
	MOV	AX, @DATA
	MOV	DS, AX

;start
	CALL	INDEC
	XOR	DX, DX

	MOV	BX, 3600
	DIV	BX

	MOV	HOUR, AX
	MOV	AX, DX
	XOR	DX, DX

	MOV	BX, 60
	DIV	BX

	MOV	MINUTE, AX
	MOV	SECOND, DX

;output
	MOV	AX, HOUR
	CALL	OUTDEC
	MOV	AH, 02H
	MOV	DL, ' '
	INT	21H

	MOV	AX, MINUTE
	CALL	OUTDEC
	MOV	AH, 02H
	MOV	DL, ' '
	INT	21H

	MOV	AX, SECOND
	CALL	OUTDEC
	MOV	AH, 02H
	MOV	DL, CR
	INT	21H
	MOV	DL, LF
	INT	21H

;dos exit
	MOV	AH, 4CH
	INT	21H

MAIN	ENDP
INCLUDE	OUTDEC.ASM	; include OUTDEC
INCLUDE	INDEC.ASM	; include INDEC
	END	MAIN
