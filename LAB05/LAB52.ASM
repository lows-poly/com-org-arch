TITLE	LAB52
.MODEL	SMALL
.STACK	100H

.DATA
CR		EQU	0DH
LF		EQU	0AH

NL		DB	CR, LF, '$'

HALF_DOL	DB	?
QUARTER		DB	?
DIME		DB	?
NICKEL		DB	?
PENNY		DB	?

.CODE
MAIN	PROC
;initialise DS
	MOV	AX, @DATA
	MOV	DS, AX

;start
	CALL	INDEC

	MOV	BL, 50
	XOR	AH, AH
	DIV	BL
	MOV	HALF_DOL, AL
	MOV	AL, AH
	
	XOR	AH, AH
	MOV	BL, 25
	DIV	BL
	MOV	QUARTER, AL
	MOV	AL, AH
	
	XOR	AH, AH
	MOV	BL, 10
	DIV	BL
	MOV	DIME, AL
	MOV	AL, AH

	XOR	AH, AH
	MOV	BL, 5
	DIV	BL
	MOV	NICKEL, AL
	MOV	PENNY, AH
;print
	XOR	AX, AX
	MOV	AL, HALF_DOL
	CALL	OUTDEC
	MOV	AH, 02H
	MOV	DL, ' '
	INT	21H

	XOR	AX, AX
	MOV	AL, QUARTER
	CALL	OUTDEC
	MOV	AH, 02H
	MOV	DL, ' '
	INT	21H

	XOR	AX, AX
	MOV	AL, DIME
	CALL	OUTDEC
	MOV	AH, 02H
	MOV	DL, ' '
	INT	21H

	XOR	AX, AX
	MOV	AL, NICKEL
	CALL	OUTDEC
	MOV	AH, 02H
	MOV	DL, ' '
	INT	21H

	XOR	AX, AX
	MOV	AL, PENNY
	CALL	OUTDEC

	MOV	AH, 02H
	MOV	DL, CR
	INT	21H
	MOV	DL, LF
	INT	21H

;dos exit
	MOV	AH, 4CH
	INT	21H

MAIN	ENDP
INCLUDE	OUTDEC.ASM	; include OUTDEC
INCLUDE	INDEC.ASM	; include INDEC
	END	MAIN
